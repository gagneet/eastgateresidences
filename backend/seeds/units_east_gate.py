async def seed_units_east_gate(clear: bool = False):
    """Seed East Gate units. Use clear=True only on fresh installs."""
    client = AsyncMongoClient(os.environ["MONGO_URL"])
    db = client[os.environ["DB_NAME"]]

    if clear:
        result = await db.units.delete_many({"building_id": "13195"})
        print(f"  Cleared {result.deleted_count} existing units")

    inserted = 0
    updated = 0
    for unit in EAST_GATE_UNITS:
        existing = await db.units.find_one({"building_id": "13195", "unit_number": unit["unit_number"]})
        if existing:
            await db.units.update_one(
                {"building_id": "13195", "unit_number": unit["unit_number"]},
                {"$set": {k: v for k, v in unit.items() if k not in ("id", "created_at")}}
            )
            updated += 1
        else:
            await db.units.insert_one(unit)
            inserted += 1
    print(f"  East Gate units: {inserted} inserted, {updated} updated")
    client.close()


