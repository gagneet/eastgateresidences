async def seed_chat_groups():
    """Upsert all chat_groups entries. Safe to re-run."""
    client = AsyncMongoClient(os.environ['MONGO_URL'])
    db = client[os.environ['DB_NAME']]
    upserted = 0
    for entry in CHAT_GROUPS:
        result = await db.chat_groups.update_one(
            {'id': entry['id']},
            {'$set': entry, '$setOnInsert': {'created_at': entry.get('created_at', entry.get('updated_at', ''))}},
            upsert=True
        )
        if result.upserted_id or result.modified_count:
            upserted += 1
    print(f'chat_groups: {upserted} upserted ({len(CHAT_GROUPS)} total)')
    client.close()


if __name__ == "__main__":
    asyncio.run(seed_chat_groups())
