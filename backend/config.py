# Encryption key for sensitive data (Fernet — AES-128-CBC + HMAC-SHA256).
# Required in every environment — no dev fallback, since a fallback key is both
# public in the repo and would silently encrypt PII with a known secret.
# Generate with: python3 -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())"
ENCRYPTION_KEY = os.getenv('ENCRYPTION_KEY')
if not ENCRYPTION_KEY:
    raise RuntimeError(
        "ENCRYPTION_KEY environment variable is required. "
        "Generate one with: python3 -c 'from cryptography.fernet import Fernet; "
        "print(Fernet.generate_key().decode())'"
    )

