# JWT Configuration
# JWT_SECRET is required in every environment. Previously this fell back to a
# hardcoded dev value unless APP_ENV == "production", which silently downgraded
# any misconfigured deploy to a key that is publicly visible in the repo.
APP_ENV = os.getenv('APP_ENV', 'development')

JWT_SECRET = os.getenv('JWT_SECRET')
if not JWT_SECRET:
    raise RuntimeError(
        "JWT_SECRET environment variable is required. "
        "Generate one with: openssl rand -base64 48"
    )

